constexpr double kPi = 3.14159265358979323846;
constexpr int kMaxQ = 9;   // Gauss points per axis at p = 7
__constant__ double c_gll[kMaxQ];

// A Gauss rule passed by value: each multigrid level has its own (q = p + 2).
struct Rule {
    double x[kMaxQ], w[kMaxQ];
};

unsigned blocks_for(long long n) { return (unsigned)((n + cellwise::kThreads - 1) / cellwise::kThreads); }

__device__ void lattice_vertex(int i, int j, int k, int ne, double deform, double x[3])
{
    x[0] = (double)i / ne;
    x[1] = (double)j / ne;
    x[2] = (double)k / ne;
    const double bump = deform * sin(kPi * x[0]) * sin(kPi * x[1]) * sin(kPi * x[2]);
    for (int d = 0; d < 3; ++d) x[d] += bump;
}

// B = 0, the plain layout: this rank's box of n[0] x n[1] x n[2] elements at element
// offset o, lexicographic (on one rank, the whole cube). Otherwise blocks of B^3 elements
// (one rank), M = ne / B per axis: element e is element (lx B + ly) B + lz of block
// e / B^3, block (mx M + my) M + mz. Rotation r of a block (0: none): its local axis d
// runs along global axis perm[d], reversed when flip[d].
struct Layout {
    int ne, B, M, rotate;
    int n[3], o[3];
};
__constant__ Layout c_layout;
__constant__ const double* c_mesh_X;   // --mesh: this rank's corners, corners_kernel's layout
__constant__ int c_rotation[24][6];   // perm[3], flip[3]

std::vector<int> proper_rotations()
{
    std::vector<int> r;
    int p[3] = {0, 1, 2};
    do {
        const int inversions = (p[0] > p[1]) + (p[0] > p[2]) + (p[1] > p[2]);
        for (int f = 0; f < 8; ++f)
            if ((inversions + (f & 1) + (f >> 1 & 1) + (f >> 2 & 1)) % 2 == 0)
                r.insert(r.end(), {p[0], p[1], p[2], f & 1, f >> 1 & 1, f >> 2 & 1});
    } while (std::next_permutation(p, p + 3));
    return r;
}

// Global lattice position of position u (0 .. extent per axis, extent = the block's
// vertices or nodes per edge) of block blk.
__device__ void place(long long blk, const int (&u)[3], int extent, long long (&g)[3])
{
    const Layout& L = c_layout;
    const int* r = c_rotation[L.rotate ? (int)(((unsigned)blk * 2654435761u >> 8) % 24) : 0];
    const long long m[3] = {blk / ((long long)L.M * L.M), (blk / L.M) % L.M, blk % L.M};
    for (int d = 0; d < 3; ++d) g[r[d]] = m[r[d]] * extent + (r[3 + d] ? extent - u[d] : u[d]);
}

__device__ void element_in_block(long long e, long long& blk, int (&l)[3])
{
    const int B = c_layout.B;
    const long long B3 = (long long)B * B * B;
    blk = e / B3;
    const int le = (int)(e % B3);
    l[0] = le / (B * B);
    l[1] = (le / B) % B;
    l[2] = le % B;
}

// Global lattice coordinates (0 .. ne P) of point x (0 .. P per axis) of element e's own
// frame at degree P: its node x, or at P = 1 its corner with bits x.
__device__ void element_point(long long e, int P, const int (&x)[3], long long (&g)[3])
{
    const Layout& L = c_layout;
    if (L.B == 0) {
        const long long l[3] = {e / ((long long)L.n[1] * L.n[2]), (e / L.n[2]) % L.n[1], e % L.n[2]};
        for (int d = 0; d < 3; ++d) g[d] = (L.o[d] + l[d]) * P + x[d];
        return;
    }
    long long blk;
    int l[3];
    element_in_block(e, blk, l);
    const int u[3] = {l[0] * P + x[0], l[1] * P + x[1], l[2] * P + x[2]};
    place(blk, u, L.B * P, g);
}

// Corners in VTK order (corner_bits) of the element's own frame.
__device__ void element_corners(long long e, int ne, double deform, double c[8][3])
{
    for (int k = 0; k < 8; ++k) {
        int b[3];
        long long g[3];
        cellwise::corner_bits(k, b[0], b[1], b[2]);
        if (c_mesh_X) {
            for (int a = 0; a < 3; ++a) c[k][a] = c_mesh_X[e * 24 + a * 8 + b[0] * 4 + b[1] * 2 + b[2]];
            continue;
        }
        element_point(e, 1, b, g);
        lattice_vertex((int)g[0], (int)g[1], (int)g[2], ne, deform, c[k]);
    }
}

// The node is on the cube's boundary.
__device__ bool boundary_node(long long e, int P, int a, int b, int c)
{
    long long g[3];
    element_point(e, P, {a, b, c}, g);
    const long long last = (long long)c_layout.ne * P;
    return g[0] == 0 || g[1] == 0 || g[2] == 0 || g[0] == last || g[1] == last || g[2] == last;
}

// The trilinear map and its Jacobian J[a][b] = dx_a / dxi_b at reference point r.
__device__ void trilinear(const double c[8][3], const double r[3], double x[3], double J[3][3])
{
    for (int a = 0; a < 3; ++a) {
        x[a] = 0.0;
        for (int b = 0; b < 3; ++b) J[a][b] = 0.0;
    }
    for (int k = 0; k < 8; ++k) {
        int bits[3];
        cellwise::corner_bits(k, bits[0], bits[1], bits[2]);
        double f[3], s[3];
        for (int d = 0; d < 3; ++d) {
            s[d] = 2.0 * bits[d] - 1.0;
            f[d] = 1.0 + s[d] * r[d];
        }
        const double w = 0.125 * f[0] * f[1] * f[2];
        const double dw[3] = {0.125 * s[0] * f[1] * f[2], 0.125 * f[0] * s[1] * f[2], 0.125 * f[0] * f[1] * s[2]};
        for (int a = 0; a < 3; ++a) {
            x[a] += w * c[k][a];
            for (int b = 0; b < 3; ++b) J[a][b] += dw[b] * c[k][a];
        }
    }
}

// One thread per (element, Gauss point): G[e][k][point], K = 1 (BP1: w det J) or 6 (BP3:
// w det J J^-1 J^-T, entries 00 01 02 11 12 22).
__global__ void geometry_kernel(double* __restrict__ G, long long E, int Q, int K, int ne, double deform, Rule rule)
{
    const long long q3 = (long long)Q * Q * Q;
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= E * q3) return;
    const long long e = t / q3;
    const int pt = (int)(t % q3), a = pt / (Q * Q), b = (pt / Q) % Q, c = pt % Q;
    double corners[8][3], x[3], J[3][3];
    element_corners(e, ne, deform, corners);
    const double r[3] = {rule.x[a], rule.x[b], rule.x[c]};
    trilinear(corners, r, x, J);
    const double det = J[0][0] * (J[1][1] * J[2][2] - J[1][2] * J[2][1]) -
                       J[0][1] * (J[1][0] * J[2][2] - J[1][2] * J[2][0]) +
                       J[0][2] * (J[1][0] * J[2][1] - J[1][1] * J[2][0]);
    const double wdet = det * rule.w[a] * rule.w[b] * rule.w[c];
    double* g = G + e * K * q3 + pt;
    if (K == 1) {
        g[0] = wdet;
        return;
    }
    double Ji[3][3];   // J^-1 = adj(J) / det
    Ji[0][0] = (J[1][1] * J[2][2] - J[1][2] * J[2][1]) / det;
    Ji[0][1] = (J[0][2] * J[2][1] - J[0][1] * J[2][2]) / det;
    Ji[0][2] = (J[0][1] * J[1][2] - J[0][2] * J[1][1]) / det;
    Ji[1][0] = (J[1][2] * J[2][0] - J[1][0] * J[2][2]) / det;
    Ji[1][1] = (J[0][0] * J[2][2] - J[0][2] * J[2][0]) / det;
    Ji[1][2] = (J[0][2] * J[1][0] - J[0][0] * J[1][2]) / det;
    Ji[2][0] = (J[1][0] * J[2][1] - J[1][1] * J[2][0]) / det;
    Ji[2][1] = (J[0][1] * J[2][0] - J[0][0] * J[2][1]) / det;
    Ji[2][2] = (J[0][0] * J[1][1] - J[0][1] * J[1][0]) / det;
    const int sym[6][2] = {{0, 0}, {0, 1}, {0, 2}, {1, 1}, {1, 2}, {2, 2}};
    for (int k = 0; k < 6; ++k) {
        const int d = sym[k][0], f = sym[k][1];
        g[k * q3] = wdet * (Ji[d][0] * Ji[f][0] + Ji[d][1] * Ji[f][1] + Ji[d][2] * Ji[f][2]);
    }
}

// X[e][a][bx][by][bz]: the corners by component, then corner bit along each reference
// axis, as the trilinear kernels read them.
__global__ void corners_kernel(double* __restrict__ X, long long E, int ne, double deform)
{
    const long long e = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (e >= E) return;
    double c[8][3];
    element_corners(e, ne, deform, c);
    for (int k = 0; k < 8; ++k) {
        int bx, by, bz;
        cellwise::corner_bits(k, bx, by, bz);
        for (int a = 0; a < 3; ++a) X[e * 24 + a * 8 + bx * 4 + by * 2 + bz] = c[k][a];
    }
}

// u = sin(pi x) sin(pi y) sin(pi z) at every copy; zero on the cube's boundary copies
// when `dirichlet` (sin vanishes there up to rounding; the copies are set exactly).
template <int P>
__global__ void exact_kernel(double* __restrict__ u, long long E, int ne, double deform, bool dirichlet)
{
    constexpr int n = P + 1, n3 = n * n * n;
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= E * n3) return;
    const long long e = t / n3;
    const int node = (int)(t % n3), a = node / (n * n), b = (node / n) % n, c = node % n;
    if (dirichlet && boundary_node(e, P, a, b, c)) {
        u[t] = 0.0;
        return;
    }
    double corners[8][3], x[3], J[3][3];
    element_corners(e, ne, deform, corners);
    const double r[3] = {c_gll[a], c_gll[b], c_gll[c]};
    trilinear(corners, r, x, J);
    u[t] = sin(kPi * x[0]) * sin(kPi * x[1]) * sin(kPi * x[2]);
}

// The GLL Lagrange basis of degree P at xi.
template <int P>
__device__ void gll_lagrange(double xi, double (&l)[P + 1])
{
    for (int i = 0; i <= P; ++i) {
        double v = 1.0;
        for (int j = 0; j <= P; ++j)
            if (j != i) v *= (xi - c_gll[j]) / (c_gll[i] - c_gll[j]);
        l[i] = v;
    }
}

// --rhs pde: (x_h - u)^2 w det J and u^2 w det J at each Gauss point (one thread each), for the
// L2 error of the discrete solution: x_h from the element's GLL values, u at the point's
// physical position. The error at the nodes alone converges one order faster.
template <int P>
__global__ void l2_kernel(const double* __restrict__ x, long long E, int ne, double deform, Rule rule,
                          double* __restrict__ e2, double* __restrict__ u2)
{
    constexpr int n = P + 1, Q = P + 2, q3 = Q * Q * Q;
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= E * q3) return;
    const long long e = t / q3;
    const int pt = (int)(t % q3), a = pt / (Q * Q), b = (pt / Q) % Q, c = pt % Q;
    double corners[8][3], xp[3], J[3][3];
    element_corners(e, ne, deform, corners);
    const double r[3] = {rule.x[a], rule.x[b], rule.x[c]};
    trilinear(corners, r, xp, J);
    const double det = J[0][0] * (J[1][1] * J[2][2] - J[1][2] * J[2][1]) -
                       J[0][1] * (J[1][0] * J[2][2] - J[1][2] * J[2][0]) +
                       J[0][2] * (J[1][0] * J[2][1] - J[1][1] * J[2][0]);
    const double w = det * rule.w[a] * rule.w[b] * rule.w[c];
    double la[n], lb[n], lc[n];
    gll_lagrange<P>(r[0], la);
    gll_lagrange<P>(r[1], lb);
    gll_lagrange<P>(r[2], lc);
    const double* xe = x + e * n * n * n;
    double xh = 0.0;
    for (int i = 0; i < n; ++i)
        for (int j = 0; j < n; ++j) {
            double sum = 0.0;
            for (int k = 0; k < n; ++k) sum += lc[k] * xe[(i * n + j) * n + k];
            xh += la[i] * lb[j] * sum;
        }
    const double u = sin(kPi * xp[0]) * sin(kPi * xp[1]) * sin(kPi * xp[2]);
    e2[t] = (xh - u) * (xh - u) * w;
    u2[t] = u * u * w;
}

// The element operator's diagonal, closed form (as cellwise_bp_ref.diagonal): BP1
// sum_q g0 phi^2, BP3 sum_q sum_rs M_rs d_r phi d_s phi, phi_ijk = B_ai B_bj B_ck, DB =
// D B the basis' derivative at the Gauss points.
template <int P>
__global__ void diagonal_kernel(const double* __restrict__ G, const double* __restrict__ B,
                                const double* __restrict__ DB, double* __restrict__ diag, long long E, int K)
{
    constexpr int n = P + 1, n3 = n * n * n, Q = P + 2, q3 = Q * Q * Q;
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= E * n3) return;
    const long long e = t / n3;
    const int node = (int)(t % n3), i = node / (n * n), j = (node / n) % n, k = node % n;
    const double* g = G + e * K * q3;
    double s = 0.0;
    for (int a = 0; a < Q; ++a)
        for (int b = 0; b < Q; ++b)
            for (int c = 0; c < Q; ++c) {
                const int pt = (a * Q + b) * Q + c;
                const double bi = B[a * n + i], bj = B[b * n + j], bk = B[c * n + k];
                if (K == 1) {
                    const double phi = bi * bj * bk;
                    s += g[pt] * phi * phi;
                    continue;
                }
                const double d0 = DB[a * n + i] * bj * bk, d1 = bi * DB[b * n + j] * bk, d2 = bi * bj * DB[c * n + k];
                s += g[pt] * d0 * d0 + g[3 * q3 + pt] * d1 * d1 + g[5 * q3 + pt] * d2 * d2 +
                     2.0 * (g[q3 + pt] * d0 * d1 + g[2 * q3 + pt] * d0 * d2 + g[4 * q3 + pt] * d1 * d2);
            }
    diag[t] = s;
}

// inv_diag = mask / diag, mask = 0 on the cube's boundary copies when `dirichlet`.
template <int P>
__global__ void inverse_kernel(const double* __restrict__ diag, double* __restrict__ inv, long long E,
                               bool dirichlet)
{
    constexpr int n = P + 1, n3 = n * n * n;
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= E * n3) return;
    const long long e = t / n3;
    const int node = (int)(t % n3), a = node / (n * n), b = (node / n) % n, c = node % n;
    inv[t] = dirichlet && boundary_node(e, P, a, b, c) ? 0.0 : 1.0 / diag[t];
}

// Corner keys: of the tables' elements by their lattice ids gid (the plain layout, own
// and ghost elements in the order of cellwise::block_elements), of the elements of the
// block layout (gid null), or of the blocks as hexes (blocks): the global lattice vertex
// of each corner, in the element's or block's own frame.
__global__ void mesh_kernel(long long count, bool blocks, const unsigned long long* __restrict__ gid,
                            unsigned long long* const* key, int* const* lid)
{
    const long long e = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (e >= count) return;
    const long long ne = c_layout.ne, side = (blocks ? c_layout.M : ne) + 1;
    for (int c = 0; c < 8; ++c) {
        int b[3];
        long long g[3];
        cellwise::corner_bits(c, b[0], b[1], b[2]);
        if (gid) {
            const long long id = (long long)gid[e];
            g[0] = id / (ne * ne) + b[0], g[1] = (id / ne) % ne + b[1], g[2] = id % ne + b[2];
        } else if (blocks) {
            place(e, b, 1, g);
        } else {
            element_point(e, 1, b, g);
        }
        const long long v = (g[0] * side + g[1]) * side + g[2];
        key[c][e] = (unsigned long long)v;
        lid[c][e] = (int)v;
    }
}

__global__ void difference_kernel(double* __restrict__ out, const double* __restrict__ a,
                                  const double* __restrict__ b, long long n)
{
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= n) return;
    const double d = a[t] - b[t];
    out[t] = isfinite(d) ? fabs(d) : INFINITY;   // the maximum reduction must not drop a NaN
}

__global__ void random_kernel(double* __restrict__ v, long long n)
{
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t >= n) return;
    unsigned long long h = (unsigned long long)t * 0x9E3779B97F4A7C15ull;
    h ^= h >> 31;
    h *= 0xBF58476D1CE4E5B9ull;
    h ^= h >> 29;
    v[t] = (double)(h >> 11) * 0x1.0p-52 - 1.0;
}

#define BP_CK(call) MARS_CELLWISE_CK(call)

// The unstructured tables of `count` elements (the first `local` this rank's, the rest
// ghosts), with the corner keys of mesh_kernel.
cellwise::UnstructuredTopology mesh_topology(long long count, long long local, bool blocks,
                                             const unsigned long long* gid, cudaStream_t stream)
{
    thrust::device_vector<unsigned long long> key[8];
    thrust::device_vector<int> lid[8];
    std::vector<unsigned long long*> kp(8);
    std::vector<int*> lp(8);
    for (int c = 0; c < 8; ++c) {
        key[c].resize(count);
        lid[c].resize(count);
        kp[c] = thrust::raw_pointer_cast(key[c].data());
        lp[c] = thrust::raw_pointer_cast(lid[c].data());
    }
    thrust::device_vector<unsigned long long*> d_kp(kp.begin(), kp.end());
    thrust::device_vector<int*> d_lp(lp.begin(), lp.end());
    mesh_kernel<<<blocks_for(count), cellwise::kThreads, 0, stream>>>(
        count, blocks, gid, thrust::raw_pointer_cast(d_kp.data()), thrust::raw_pointer_cast(d_lp.data()));
    BP_CK(cudaStreamSynchronize(stream));
    const std::vector<const unsigned long long*> ckp(kp.begin(), kp.end());
    const std::vector<const int*> clp(lp.begin(), lp.end());
    thrust::device_vector<const unsigned long long*> d_ckp(ckp.begin(), ckp.end());
    thrust::device_vector<const int*> d_clp(clp.begin(), clp.end());
    return cellwise::build_topology(thrust::raw_pointer_cast(d_ckp.data()), thrust::raw_pointer_cast(d_clp.data()),
                                    count, local);
}

// --mesh: one rank's tables of an Exodus Hex8 mesh (see the header). key[e * 8 + c]: the
// file's (0-based) vertex of corner c of table element e; gid: the file's element index.
struct MeshTables {
    long long local = 0, global = 0, mirrored = 0;
    std::vector<unsigned long long> gid, key;
    std::vector<int> owner;
    std::vector<double> X;   // this rank's elements' corners, corners_kernel's layout
};

template <typename T>
void bcast(std::vector<T>& v, MPI_Comm comm)
{
    long long size = (long long)v.size();
    MARS_CELLWISE_MPI(MPI_Bcast(&size, 1, MPI_LONG_LONG, 0, comm));
    v.resize(size);
    constexpr long long chunk = 1LL << 27;   // MPI counts are int
    for (long long i = 0; i < size; i += chunk)
        MARS_CELLWISE_MPI(
            MPI_Bcast(v.data() + i, (int)(std::min(chunk, size - i) * (long long)sizeof(T)), MPI_BYTE, 0, comm));
}

unsigned long long morton_spread(unsigned long long v)   // 21 bits, two zeros between
{
    v &= 0x1fffffULL;
    v = (v | v << 32) & 0x1f00000000ffffULL;
    v = (v | v << 16) & 0x1f0000ff0000ffULL;
    v = (v | v << 8) & 0x100f00f00f00f00fULL;
    v = (v | v << 4) & 0x10c30c30c30c30c3ULL;
    v = (v | v << 2) & 0x1249249249249249ULL;
    return v;
}

MeshTables mesh_tables(const std::string& path, MPI_Comm comm)
{
    int rank = 0, size = 1;
    MARS_CELLWISE_MPI(MPI_Comm_rank(comm, &rank));
    MARS_CELLWISE_MPI(MPI_Comm_size(comm, &size));
    mars::ExodusRawHex8 m;
    if (rank == 0) m = mars::readExodusHex8Raw(path);
    for (auto& c : m.coordinates) bcast(c, comm);
    bcast(m.connectivity, comm);
    const auto& X = m.coordinates;
    auto& C = m.connectivity;
    const long long ne = (long long)C.size() / 8, nv = (long long)X[0].size();
    if (nv > 0x7fffffffLL || ne > 0x7fffffffLL) {   // int vertex and element ids below
        if (rank == 0) fprintf(stderr, "--mesh: %lld vertices, %lld elements: more than an int holds\n", nv, ne);
        MPI_Abort(comm, 1);
    }
    MeshTables t;
    t.global = ne;
    auto corner = [&](long long e, int k, int a) { return X[a][C[e * 8 + k] - 1]; };

    // A negative Jacobian at the center (left-handed corner order): mirror the element by
    // swapping corners 1 <-> 3 and 5 <-> 7 (exchanges the first two reference axes).
    for (long long e = 0; e < ne; ++e) {
        double d[3][3];
        for (int a = 0; a < 3; ++a) {
            d[0][a] = corner(e, 1, a) + corner(e, 2, a) + corner(e, 5, a) + corner(e, 6, a) - corner(e, 0, a) -
                      corner(e, 3, a) - corner(e, 4, a) - corner(e, 7, a);
            d[1][a] = corner(e, 2, a) + corner(e, 3, a) + corner(e, 6, a) + corner(e, 7, a) - corner(e, 0, a) -
                      corner(e, 1, a) - corner(e, 4, a) - corner(e, 5, a);
            d[2][a] = corner(e, 4, a) + corner(e, 5, a) + corner(e, 6, a) + corner(e, 7, a) - corner(e, 0, a) -
                      corner(e, 1, a) - corner(e, 2, a) - corner(e, 3, a);
        }
        const double det = d[0][0] * (d[1][1] * d[2][2] - d[1][2] * d[2][1]) -
                           d[0][1] * (d[1][0] * d[2][2] - d[1][2] * d[2][0]) +
                           d[0][2] * (d[1][0] * d[2][1] - d[1][1] * d[2][0]);
        if (det < 0.0) {
            std::swap(C[e * 8 + 1], C[e * 8 + 3]);
            std::swap(C[e * 8 + 5], C[e * 8 + 7]);
            ++t.mirrored;
        }
    }

    // The partition: Morton order of the centroids in the bounding box, equal chunks.
    double lo[3], hi[3];
    for (int a = 0; a < 3; ++a) {
        lo[a] = *std::min_element(X[a].begin(), X[a].end());
        hi[a] = *std::max_element(X[a].begin(), X[a].end());
    }
    std::vector<std::pair<unsigned long long, long long>> order(ne);
    for (long long e = 0; e < ne; ++e) {
        unsigned long long key = 0;
        for (int a = 0; a < 3; ++a) {
            double c = 0.0;
            for (int k = 0; k < 8; ++k) c += corner(e, k, a);
            const double f = (c / 8.0 - lo[a]) / (hi[a] - lo[a]);
            key |= morton_spread((unsigned long long)std::min(2097151.0, std::max(0.0, f * 2097152.0))) << (2 - a);
        }
        order[e] = {key, e};
    }
    std::sort(order.begin(), order.end());
    auto first = [&](int r) { return ne / size * r + std::min<long long>(r, ne % size); };
    std::vector<int> owner(ne);
    for (int r = 0; r < size; ++r)
        for (long long i = first(r); i < first(r + 1); ++i) owner[order[i].second] = r;

    // Ghosts: the elements sharing a vertex with this rank's.
    std::vector<long long> voff(nv + 1, 0);
    for (long long v : C) ++voff[v];
    for (long long v = 0; v < nv; ++v) voff[v + 1] += voff[v];
    std::vector<int> vel(C.size());
    {
        std::vector<long long> fill(voff.begin(), voff.end() - 1);
        for (long long e = 0; e < ne; ++e)
            for (int k = 0; k < 8; ++k) vel[fill[C[e * 8 + k] - 1]++] = (int)e;
    }
    std::vector<long long> table;
    for (long long i = first(rank); i < first(rank + 1); ++i) table.push_back(order[i].second);
    t.local = (long long)table.size();
    std::vector<char> seen(ne, 0);
    std::vector<long long> ghosts;
    for (long long i = 0; i < t.local; ++i)
        for (int k = 0; k < 8; ++k) {
            const long long v = C[table[i] * 8 + k] - 1;
            for (long long j = voff[v]; j < voff[v + 1]; ++j) {
                const int g = vel[j];
                if (owner[g] != rank && !seen[g]) {
                    seen[g] = 1;
                    ghosts.push_back(g);
                }
            }
        }
    std::sort(ghosts.begin(), ghosts.end());
    table.insert(table.end(), ghosts.begin(), ghosts.end());

    for (long long e : table) {
        t.gid.push_back((unsigned long long)e);
        t.owner.push_back(owner[e]);
        for (int k = 0; k < 8; ++k) t.key.push_back((unsigned long long)(C[e * 8 + k] - 1));
    }
    t.X.resize(t.local * 24);
    for (long long i = 0; i < t.local; ++i)
        for (int k = 0; k < 8; ++k) {
            int b[3];
            cellwise::corner_bits(k, b[0], b[1], b[2]);
            for (int a = 0; a < 3; ++a) t.X[i * 24 + a * 8 + b[0] * 4 + b[1] * 2 + b[2]] = corner(table[i], k, a);
        }
    return t;
}

// The unstructured tables of a MeshTables (local elements first).
cellwise::UnstructuredTopology mesh_file_topology(const MeshTables& t)
{
    const long long count = (long long)t.gid.size();
    thrust::device_vector<unsigned long long> key[8];
    thrust::device_vector<int> lid[8];
    std::vector<const unsigned long long*> kp(8);
    std::vector<const int*> lp(8);
    std::vector<unsigned long long> hk(count);
    std::vector<int> hl(count);
    for (int c = 0; c < 8; ++c) {
        for (long long e = 0; e < count; ++e) {
            hk[e] = t.key[e * 8 + c];
            hl[e] = (int)hk[e];   // vertex ids fit an int (checked by the caller)
        }
        key[c] = hk;
        lid[c] = hl;
        kp[c] = thrust::raw_pointer_cast(key[c].data());
        lp[c] = thrust::raw_pointer_cast(lid[c].data());
    }
    thrust::device_vector<const unsigned long long*> d_kp(kp.begin(), kp.end());
    thrust::device_vector<const int*> d_lp(lp.begin(), lp.end());
    return cellwise::build_topology(thrust::raw_pointer_cast(d_kp.data()), thrust::raw_pointer_cast(d_lp.data()),
                                    count, t.local);
}

template <int P>
void block_dss(int B, const double* in, double* out, const cellwise::BlockSkeleton& S, bool nodes, cudaStream_t st)
{
    switch (B) {
    case 2: cellwise::block_dss<P, 2>(in, out, S, nodes, st); break;
    case 4: cellwise::block_dss<P, 4>(in, out, S, nodes, st); break;
    case 8: cellwise::block_dss<P, 8>(in, out, S, nodes, st); break;
    case 16: cellwise::block_dss<P, 16>(in, out, S, nodes, st); break;
    default: cellwise::block_dss<P, 32>(in, out, S, nodes, st); break;
    }
    BP_CK(cudaGetLastError());
}

// The 1D matrices at degree P with q = P + 2 Gauss points: B (GLL basis at the Gauss
// points), D (Gauss-point derivative), their transposes, DB = D B for the diagonal.
struct Basis {
    std::vector<double> zeta, gq, wq, B, Bt, D, Dt, DB;
};

Basis basis(int P)
{
    const int n = P + 1, Q = P + 2;
    Basis b;
    std::vector<double> wgll, Dgll, val, der;
    fem::gllBasis(P, b.zeta, wgll, Dgll);
    fem::gaussLegendre(Q, b.gq, b.wq);
    b.B.resize(Q * n), b.Bt.resize(n * Q), b.D.resize(Q * Q), b.Dt.resize(Q * Q), b.DB.assign(Q * n, 0.0);
    for (int a = 0; a < Q; ++a) {
        fem::lagrangeValDeriv(b.zeta, b.gq[a], val, der);
        for (int i = 0; i < n; ++i) b.B[a * n + i] = b.Bt[i * Q + a] = val[i];
        fem::lagrangeValDeriv(b.gq, b.gq[a], val, der);
        for (int k = 0; k < Q; ++k) b.D[a * Q + k] = b.Dt[k * Q + a] = der[k];
    }
    for (int a = 0; a < Q; ++a)
        for (int i = 0; i < n; ++i)
            for (int m = 0; m < Q; ++m) b.DB[a * n + i] += b.D[a * Q + m] * b.B[m * n + i];
    return b;
}

Rule rule_of(const Basis& b)
{
    Rule r{};
    for (size_t a = 0; a < b.gq.size(); ++a) r.x[a] = b.gq[a], r.w[a] = b.wq[a];
    return r;
}

// A coarser BP3 level of the multigrid: the same mesh at degree PL (q = PL + 2), stored
// geometry, the MARSIR operator bp3_p{PL} and the element diagonal.
struct Bp3Level {
    thrust::device_vector<double> B, Bt, D, Dt, DB, G, elem;
    std::unique_ptr<marsir::GalerkinPtx> op;
    long long E = 0;

    void apply(const double* u, double* y, cudaStream_t st) const
    {
        auto c = [](const thrust::device_vector<double>& v) { return thrust::raw_pointer_cast(v.data()); };
        op->apply(u, c(B), c(Bt), c(D), c(Dt), c(G), y, E, st);
    }
};

template <int PL>
std::unique_ptr<Bp3Level> bp3_level(const std::string& ptx_dir, long long E, int ne, double deform, cudaStream_t st)
{
    constexpr int n3 = (PL + 1) * (PL + 1) * (PL + 1), Q = PL + 2, q3 = Q * Q * Q;
    const Basis b = basis(PL);
    auto L = std::make_unique<Bp3Level>();
    L->E = E;
    L->B = b.B, L->Bt = b.Bt, L->D = b.D, L->Dt = b.Dt, L->DB = b.DB;
    L->G.resize(E * 6 * q3);
    L->elem.resize(E * n3);
    auto c = [](thrust::device_vector<double>& v) { return thrust::raw_pointer_cast(v.data()); };
    geometry_kernel<<<blocks_for(E * q3), cellwise::kThreads, 0, st>>>(c(L->G), E, Q, 6, ne, deform, rule_of(b));
    diagonal_kernel<PL><<<blocks_for(E * n3), cellwise::kThreads, 0, st>>>(c(L->G), c(L->B), c(L->DB), c(L->elem), E, 6);
    MARS_CELLWISE_CK(cudaGetLastError());
    L->op = std::make_unique<marsir::GalerkinPtx>(ptx_dir + "/bp3_p" + std::to_string(PL) + "_sm90.ptx",
                                                  "bp3_apply_p" + std::to_string(PL), PL, Q, true, 6);
    return L;
}

__global__ void scale_kernel(double* __restrict__ v, long long n, double s)
{
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t < n) v[t] *= s;
}

// out = b - y.
__global__ void residual_kernel(double* __restrict__ out, const double* __restrict__ b, const double* __restrict__ y,
                                long long n)
{
    const long long t = (long long)blockIdx.x * blockDim.x + threadIdx.x;
    if (t < n) out[t] = b[t] - y[t];
}

double all_sum(double v)
{
    MARS_CELLWISE_MPI(MPI_Allreduce(MPI_IN_PLACE, &v, 1, MPI_DOUBLE, MPI_SUM, MPI_COMM_WORLD));
    return v;
}

double all_max(double v)
{
    MARS_CELLWISE_MPI(MPI_Allreduce(MPI_IN_PLACE, &v, 1, MPI_DOUBLE, MPI_MAX, MPI_COMM_WORLD));
    return v;
}

// sqrt of the sum over global nodes of v^2 (each node once: its counting copy, on the
// rank that holds it).
template <int P>
double counted_norm(const double* v, const cellwise::UnstructuredTopology& T, cudaStream_t st)
{
    static const int grid = cellwise::resident_grid(cellwise::level_wdot_kernel<P>);
    thrust::device_vector<double> partial(grid);
    cellwise::level_wdot_kernel<P><<<grid, cellwise::kThreads, 0, st>>>(
        v, v, cellwise::topo_detail::raw(T.counting), T.local, thrust::raw_pointer_cast(partial.data()));
    MARS_CELLWISE_CK(cudaStreamSynchronize(st));
    return std::sqrt(all_sum(thrust::reduce(partial.begin(), partial.end(), 0.0)));
}

struct Options {
    std::string ptx_dir, spec = "bp3", dss_ptx, block_dss;   // block_dss: "", "passes" or "nodes"
    // (2,2) smoothing and 3 AMG cycles: the fastest measured at equal accuracy at p = 3 and 7,
    // about 1% from the best at p = 1 (docs/design/cellwise_bp_fcg.md).
    int p = 3, ne = 32, maxit = 2000, reps = 20, block = 0, pre = 2, post = 2, coarse = 100, amg_cycles = 3;
    int solves = 1;
    bool rotate = false, mg = false, amg = false, amg_print = false, profile = false, p1_matrix_free = false;
    bool p1_assembled = false;   // set from the others after parsing
    std::string cheb_interval = "mars", rhs = "discrete", mesh;
    double deform = 0.05, tol = 1e-10;
    // BoomerAMG's hierarchy (cellwise::AmgSettings; these defaults are its own).
    double amg_theta = 0.25;
    int amg_agg = 0, amg_coarse_size = 9;
};

template <int P>
int run(const Options& o)
{
    constexpr int n = P + 1, n3 = n * n * n, Q = P + 2, q3 = Q * Q * Q;
    const bool bp3 = o.spec.rfind("bp3", 0) == 0, tri = o.spec.substr(3) == "_tri";
    const int K = bp3 ? 6 : 1;
    const cellwise::Decomposition dec(MPI_COMM_WORLD, o.ne, o.ne, o.ne);
    const bool root = dec.rank == 0;
    const cellwise::Block& box = dec.local;
    const bool meshed = !o.mesh.empty();
    MeshTables mt;
    double read_s = 0.0;
    if (meshed) {
        const auto m0 = std::chrono::steady_clock::now();
        mt = mesh_tables(o.mesh, MPI_COMM_WORLD);
        read_s = all_max(std::chrono::duration<double>(std::chrono::steady_clock::now() - m0).count());
    }
    const long long E = meshed ? mt.local : box.elements(), N = E * n3;   // this rank's elements and copies
    long long N_all = N;
    MARS_CELLWISE_MPI(MPI_Allreduce(MPI_IN_PLACE, &N_all, 1, MPI_LONG_LONG, MPI_SUM, MPI_COMM_WORLD));
    long long unique = (long long)(o.ne * P + 1) * (o.ne * P + 1) * (o.ne * P + 1);   // --mesh: from the tables

    const Basis fine = basis(P);
    const std::vector<double>&B = fine.B, &Bt = fine.Bt, &D = fine.D, &Dt = fine.Dt, &DB = fine.DB, &gq = fine.gq,
                             &wq = fine.wq;
    BP_CK(cudaMemcpyToSymbol(c_gll, fine.zeta.data(), n * sizeof(double)));
    const int Bk = o.block ? o.block : o.ne;
    const bool blocked = o.block || o.rotate || !o.block_dss.empty();   // the block layout (one rank)
    const Layout layout{o.ne, blocked ? Bk : 0, o.ne / Bk, o.rotate ? 1 : 0, {box.nx, box.ny, box.nz},
                        {box.ox, box.oy, box.oz}};
    const std::vector<int> rotations = proper_rotations();
    BP_CK(cudaMemcpyToSymbol(c_layout, &layout, sizeof(layout)));
    BP_CK(cudaMemcpyToSymbol(c_rotation, rotations.data(), rotations.size() * sizeof(int)));
    thrust::device_vector<double> dB(B), dBt(Bt), dD(D), dDt(Dt), dDB(DB), dgq(gq), dwq(wq);
    auto raw = [](thrust::device_vector<double>& v) { return thrust::raw_pointer_cast(v.data()); };
    thrust::device_vector<double> mesh_X(mt.X.begin(), mt.X.end());
    {
        const double* p = meshed ? raw(mesh_X) : nullptr;
        BP_CK(cudaMemcpyToSymbol(c_mesh_X, &p, sizeof(p)));
    }

    cudaStream_t stream;
    BP_CK(cudaStreamCreateWithFlags(&stream, cudaStreamNonBlocking));
    thrust::device_vector<double> G(E * K * q3), u(N), y(N), b(N), x(N), diag(N), inv(N), s(N), r(N), q(N), z(N),
        pdir(N), ones(N, 1.0), X(tri ? E * 24 : 0);
    geometry_kernel<<<blocks_for(E * q3), cellwise::kThreads, 0, stream>>>(raw(G), E, Q, K, o.ne, o.deform,
                                                                         rule_of(fine));
    BP_CK(cudaGetLastError());
    if (tri) {
        corners_kernel<<<blocks_for(E), cellwise::kThreads, 0, stream>>>(raw(X), E, o.ne, o.deform);
        BP_CK(cudaGetLastError());
    }

    const std::string kernel = o.spec + "_apply_p" + std::to_string(P);
    const std::string path = o.ptx_dir + "/" + o.spec + "_p" + std::to_string(P) + "_sm90.ptx";
    marsir::GalerkinPtx op(path, kernel, P, Q, bp3, tri ? 0 : K);
    auto apply = [&](const double* in, double* out, cudaStream_t st) {
        if (tri) op.apply_trilinear(in, raw(dB), raw(dBt), raw(dD), raw(dDt), raw(dgq), raw(dwq), raw(X), out, E, st);
        else op.apply(in, raw(dB), raw(dBt), raw(dD), raw(dDt), raw(G), out, E, st);
    };

    // The unstructured tables: in the plain layout of this rank's elements and the ghost
    // elements around them (gid, owner: their lattice ids and owner ranks), in the block
    // layout of its elements; with --block-dss also of the blocks.
    thrust::device_vector<unsigned long long> gid;
    thrust::device_vector<int> owner;
    if (meshed) {
        gid.assign(mt.gid.begin(), mt.gid.end());
        owner.assign(mt.owner.begin(), mt.owner.end());
    } else if (!blocked) {
        cellwise::block_elements(dec, gid, owner);
    }
    const unsigned long long* d_gid = blocked ? nullptr : thrust::raw_pointer_cast(gid.data());
    const cellwise::UnstructuredTopology topo =
        meshed ? mesh_file_topology(mt) : mesh_topology(blocked ? E : (long long)gid.size(), E, false, d_gid, stream);
    if (meshed) {   // every node once (its counting copy), Dirichlet ones included
        const double c = counted_norm<P>(raw(ones), topo, stream);
        unique = std::llround(c * c);
    }
    const long long nblocks = (long long)layout.M * layout.M * layout.M;
    const cellwise::UnstructuredTopology skeleton_topo =
        !o.block_dss.empty() ? mesh_topology(nblocks, nblocks, true, nullptr, stream) : cellwise::UnstructuredTopology{};
    // On several ranks the exchanges at p, and for the multigrid at 3 and 1.
    std::unique_ptr<cellwise::UnstructuredHalo> halo, halo3, halo1;
    if (dec.size > 1) {
        const int* d_owner = thrust::raw_pointer_cast(owner.data());
        halo.reset(new cellwise::UnstructuredHalo(topo, d_gid, d_owner, MPI_COMM_WORLD, P));
        if (o.mg && P == 7) halo3.reset(new cellwise::UnstructuredHalo(topo, d_gid, d_owner, MPI_COMM_WORLD, 3));
        if (o.mg && P > 1) halo1.reset(new cellwise::UnstructuredHalo(topo, d_gid, d_owner, MPI_COMM_WORLD, 1));
    }
    cellwise::UnstructuredHalo* const h = halo.get();
    cellwise::UnstructuredHalo* const h3 = P == 3 ? h : halo3.get();
    cellwise::UnstructuredHalo* const h1 = P == 1 ? h : halo1.get();
    // The tables and halos were built on the default stream, which `stream` does not wait for.
    BP_CK(cudaDeviceSynchronize());
    const cellwise::BlockSkeleton skeleton{
        cellwise::topo_detail::raw(skeleton_topo.face_nbr), cellwise::topo_detail::raw(skeleton_topo.edge_off),
        cellwise::topo_detail::raw(skeleton_topo.edge_ent), cellwise::topo_detail::raw(skeleton_topo.vert_off),
        cellwise::topo_detail::raw(skeleton_topo.vert_ent), cellwise::topo_detail::raw(skeleton_topo.face_code),
        nblocks, o.block_dss.empty() ? 0 : skeleton_topo.edges(), o.block_dss.empty() ? 0 : skeleton_topo.vertices()};
    std::unique_ptr<marsir::DssPtx> dss_gen(o.dss_ptx.empty() ? nullptr : new marsir::DssPtx(o.dss_ptx, P));
    std::unique_ptr<marsir::BlockDssPtx> block_gen(
        o.block_dss == "generated" ? new marsir::BlockDssPtx(o.ptx_dir + "/block_dss_p" + std::to_string(P) + "_b" +
                                                                 std::to_string(Bk) + "_sm90.ptx",
                                                             P, Bk)
                                   : nullptr);
    auto dss = [&topo, &skeleton, &skeleton_topo, gen = dss_gen.get(), bgen = block_gen.get(), E, Bk, h,
                block = !o.block_dss.empty(), nodes = o.block_dss != "passes"](const double* in, double* out,
                                                                                 cudaStream_t st) {
        if (bgen) bgen->run(in, out, skeleton_topo, st);
        else if (block) block_dss<P>(Bk, in, out, skeleton, nodes, st);
        else if (gen) gen->run(in, nullptr, out, topo, cellwise::ElementList{nullptr, E}, st);
        else cellwise::dss<P>(in, out, topo, h, st);
    };
    // The block DSS against the hand gather on a random vector.
    double block_err = 0.0, block_scale = 0.0;
    if (!o.block_dss.empty()) {
        random_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(y), N);
        cellwise::dss<P>(raw(y), raw(r), topo, nullptr, stream);
        dss(raw(y), raw(q), stream);
        difference_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(z), raw(r), raw(q), N);
        BP_CK(cudaStreamSynchronize(stream));
        block_err = thrust::reduce(z.begin(), z.end(), 0.0, thrust::maximum<double>());
        std::vector<double> hr(N);
        thrust::copy(r.begin(), r.end(), hr.begin());
        for (double v : hr) block_scale = std::isfinite(v) ? std::fmax(block_scale, std::fabs(v)) : INFINITY;
    }
    // The generated block DSS against the hand block nodes, bit for bit.
    long long block_bits = 0;
    if (block_gen) {
        block_dss<P>(Bk, raw(y), raw(pdir), skeleton, true, stream);
        BP_CK(cudaStreamSynchronize(stream));
        std::vector<double> hq(N), hh(N);
        thrust::copy(q.begin(), q.end(), hq.begin());
        thrust::copy(pdir.begin(), pdir.end(), hh.begin());
        for (long long i = 0; i < N; ++i) block_bits += std::memcmp(&hq[i], &hh[i], sizeof(double)) != 0;
    }

    // Checks of the operator: BP1 applied to 1 sums to the volume, BP3 applied to 1 is 0, and
    // on a random v (in x; A v in z, both free until the solve) the first elements equal
    // direct quadrature sums. The rounding is of the size of |A| |v|, so both are relative to
    // max |A v|: relative to A u, which shrinks like h^2 while the rounding shrinks like h,
    // they tightened as the mesh was refined.
    apply(raw(ones), raw(y), stream);
    random_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(x), N);
    BP_CK(cudaGetLastError());
    apply(raw(x), raw(z), stream);
    BP_CK(cudaStreamSynchronize(stream));
    const double sum1 = all_sum(thrust::reduce(y.begin(), y.end(), 0.0));
    exact_kernel<P><<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(u), E, o.ne, o.deform, bp3 && !meshed);
    BP_CK(cudaGetLastError());
    if (meshed) cellwise::zero_dirichlet<P>(raw(u), topo, stream);   // the boundary from the tables
    apply(raw(u), raw(b), stream);   // b = A u
    const bool pde = o.rhs == "pde";
    std::unique_ptr<marsir::GalerkinPtx> mass;
    thrust::device_vector<double> G1;
    auto apply_mass = [&](const double* in, double* out) {
        mass->apply(in, raw(dB), raw(dBt), raw(dD), raw(dDt), raw(G1), out, E, stream);
    };
    if (pde) {
        G1.resize(E * q3);
        geometry_kernel<<<blocks_for(E * q3), cellwise::kThreads, 0, stream>>>(raw(G1), E, Q, 1, o.ne, o.deform,
                                                                              rule_of(fine));
        BP_CK(cudaGetLastError());
        mass.reset(new marsir::GalerkinPtx(o.ptx_dir + "/bp1_p" + std::to_string(P) + "_sm90.ptx",
                                           "bp1_apply_p" + std::to_string(P), P, Q, false, 1));
        apply_mass(raw(u), raw(b));
        scale_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(b), N, 3.0 * kPi * kPi);
        BP_CK(cudaGetLastError());
    }
    BP_CK(cudaStreamSynchronize(stream));
    double max1 = 0.0, maxv = 0.0;
    {
        std::vector<double> hy(N), hz(N);
        thrust::copy(y.begin(), y.end(), hy.begin());
        thrust::copy(z.begin(), z.end(), hz.begin());
        for (long long i = 0; i < N; ++i) {
            max1 = std::fmax(max1, std::fabs(hy[i]));
            maxv = std::fmax(maxv, std::fabs(hz[i]));
        }
        max1 = all_max(max1);
        maxv = all_max(maxv);
    }
    // The first elements against direct quadrature sums on the host.
    const long long Ec = std::min<long long>(E, 4);
    double oracle_err = 0.0, oracle_scale = 0.0;
    {
        std::vector<double> hu(Ec * n3), hb(Ec * n3), hG(Ec * K * q3);   // v and A v
        thrust::copy(x.begin(), x.begin() + Ec * n3, hu.begin());
        thrust::copy(z.begin(), z.begin() + Ec * n3, hb.begin());
        thrust::copy(G.begin(), G.begin() + Ec * K * q3, hG.begin());
        const int sym[3][3] = {{0, 1, 2}, {1, 3, 4}, {2, 4, 5}};
        for (long long e = 0; e < Ec; ++e) {
            std::vector<double> uq(q3, 0.0), d[3], w(q3, 0.0);
            for (int pt = 0; pt < q3; ++pt) {
                const int a = pt / (Q * Q), bb = (pt / Q) % Q, c = pt % Q;
                for (int node = 0; node < n3; ++node)
                    uq[pt] += B[a * n + node / (n * n)] * B[bb * n + (node / n) % n] * B[c * n + node % n] *
                              hu[e * n3 + node];
            }
            const double* g = &hG[e * K * q3];
            if (!bp3) {
                for (int pt = 0; pt < q3; ++pt) w[pt] = g[pt] * uq[pt];
            } else {
                for (int rr = 0; rr < 3; ++rr) d[rr].assign(q3, 0.0);
                for (int pt = 0; pt < q3; ++pt) {
                    const int a = pt / (Q * Q), bb = (pt / Q) % Q, c = pt % Q;
                    for (int m = 0; m < Q; ++m) {
                        d[0][pt] += D[a * Q + m] * uq[(m * Q + bb) * Q + c];
                        d[1][pt] += D[bb * Q + m] * uq[(a * Q + m) * Q + c];
                        d[2][pt] += D[c * Q + m] * uq[(a * Q + bb) * Q + m];
                    }
                }
                std::vector<double> dv[3];
                for (int rr = 0; rr < 3; ++rr) {
                    dv[rr].assign(q3, 0.0);
                    for (int pt = 0; pt < q3; ++pt)
                        for (int ss = 0; ss < 3; ++ss) dv[rr][pt] += g[sym[rr][ss] * q3 + pt] * d[ss][pt];
                }
                for (int pt = 0; pt < q3; ++pt) {
                    const int a = pt / (Q * Q), bb = (pt / Q) % Q, c = pt % Q;
                    for (int m = 0; m < Q; ++m)
                        w[pt] += D[m * Q + a] * dv[0][(m * Q + bb) * Q + c] + D[m * Q + bb] * dv[1][(a * Q + m) * Q + c] +
                                 D[m * Q + c] * dv[2][(a * Q + bb) * Q + m];
                }
            }
            for (int node = 0; node < n3; ++node) {
                double sum = 0.0;
                for (int pt = 0; pt < q3; ++pt) {
                    const int a = pt / (Q * Q), bb = (pt / Q) % Q, c = pt % Q;
                    sum += B[a * n + node / (n * n)] * B[bb * n + (node / n) % n] * B[c * n + node % n] * w[pt];
                }
                oracle_err = std::fmax(oracle_err, std::fabs(sum - hb[e * n3 + node]));
                oracle_scale = std::fmax(oracle_scale, std::fabs(sum));
            }
        }
        oracle_err = all_max(oracle_err);
        oracle_scale = all_max(oracle_scale);
    }

    // The preconditioner: the assembled diagonal on every copy, inverted, Dirichlet zeroed.
    diagonal_kernel<P><<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(G), raw(dB), raw(dDB), raw(s), E, K);
    BP_CK(cudaGetLastError());
    dss(raw(s), raw(diag), stream);
    inverse_kernel<P><<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(diag), raw(inv), E, bp3 && !meshed);
    if (meshed) cellwise::zero_dirichlet<P>(raw(inv), topo, stream);
    BP_CK(cudaGetLastError());
    const cellwise::DssJacobi<decltype(dss)> precond{dss, raw(inv), raw(s), N};
    cudaEvent_t t0, t1;
    BP_CK(cudaEventCreate(&t0));
    BP_CK(cudaEventCreate(&t1));

    // --mg: the levels below p, the V-cycle, and on p = 1 Chebyshev steps or BoomerAMG.
    using LevelApply = std::function<void(const double*, double*, cudaStream_t)>;
    using Multigrid = cellwise::PMultigrid<LevelApply>;
    std::unique_ptr<Bp3Level> L3, L1;
    std::unique_ptr<Multigrid> mg;
    // Host time in the BoomerAMG setup and solves (a solve with its two p = 1 DSS),
    // synchronized at both ends; the solve synchronizes inside anyway.
    double coarse_s = 0.0, amg_setup_ms = 0.0;
#ifdef MARS_ENABLE_HYPRE
    std::unique_ptr<cellwise::P1Amg> amg;
    auto coarse = [&](const double* in, double* out) {
        BP_CK(cudaStreamSynchronize(stream));
        const auto c0 = std::chrono::steady_clock::now();
        amg->solve(in, out);
        BP_CK(cudaStreamSynchronize(stream));
        coarse_s += std::chrono::duration<double>(std::chrono::steady_clock::now() - c0).count();
    };
#endif
    thrust::device_vector<double> elem_fine;
    float setup_ms = 0.0f;
    std::array<double, 3> lmax{};
    if (o.mg) {
        BP_CK(cudaEventRecord(t0, stream));
        // The fine element diagonal (s is scratch from here on). The copy runs on the
        // default stream, which does not wait for the non-blocking one that wrote s.
        BP_CK(cudaStreamSynchronize(stream));
        elem_fine = s;
        if constexpr (P == 7) L3 = bp3_level<3>(o.ptx_dir, E, o.ne, o.deform, stream);
        if constexpr (P > 1) L1 = bp3_level<1>(o.ptx_dir, E, o.ne, o.deform, stream);
        auto level_apply = [&](int lp, const double* in, double* out, cudaStream_t st) {
            if (lp == P) apply(in, out, st);
            else if (lp == 3) L3->apply(in, out, st);
            else L1->apply(in, out, st);
        };
        auto level_elem = [&](int lp) -> const double* {
            return lp == P ? raw(elem_fine) : (lp == 3 ? raw(L3->elem) : raw(L1->elem));
        };
        if constexpr (P > 1) {
            mg = std::make_unique<Multigrid>(P, level_apply, level_elem, topo,
                                             std::array<cellwise::UnstructuredHalo*, 3>{P == 7 ? h : nullptr, h3, h1},
                                             d_gid, o.pre, o.post, o.coarse, MPI_COMM_WORLD, stream,
                                             o.cheb_interval == "mfem" ? cellwise::ChebyshevInterval::mfem()
                                                                       : cellwise::ChebyshevInterval{});
            lmax = mg->lambda_max();
        }
#ifdef MARS_ENABLE_HYPRE
        if (o.amg) {
            const LevelApply apply1 = P == 1 ? LevelApply(apply)
                                             : LevelApply([&](const double* in, double* out, cudaStream_t st) {
                                                   L1->apply(in, out, st);
                                               });
            BP_CK(cudaStreamSynchronize(stream));
            const auto a0 = std::chrono::steady_clock::now();
            amg = std::make_unique<cellwise::P1Amg>(
                topo, apply1, h1, MPI_COMM_WORLD, stream, o.amg_cycles,
                cellwise::AmgSettings{o.amg_theta, o.amg_agg, o.amg_coarse_size, o.amg_print});
            BP_CK(cudaStreamSynchronize(stream));
            amg_setup_ms = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - a0).count();
            if (mg) mg->set_coarse_solve(coarse);
        }
#endif
        BP_CK(cudaEventRecord(t1, stream));
        BP_CK(cudaEventSynchronize(t1));
        BP_CK(cudaEventElapsedTime(&setup_ms, t0, t1));
    }
    if (tri) {
        BP_CK(cudaStreamSynchronize(stream));
        G.clear();
        G.shrink_to_fit();
    }

    cellwise::FcgReduction red(MPI_COMM_WORLD);
    auto solve = [&](const auto& pc) {
        return cellwise::fcg(apply, pc, raw(b), raw(x), N, raw(r), raw(q), raw(z), raw(pdir), red, o.tol, o.maxit,
                             stream);
    };
    cellwise::FcgResult res;
    float solve_ms = 0.0f;
    std::vector<float> solve_times;
    auto cycle = [&](const double* in, double* out, cudaStream_t) {
        if (mg) mg->cycle(in, out);
#ifdef MARS_ENABLE_HYPRE
        else coarse(in, out);
#endif
    };
    long long m = 0;   // p1_assembled: this rank's rows
#ifdef MARS_ENABLE_HYPRE
    if (o.p1_assembled) m = amg->rows();
    thrust::device_vector<double> rb(m), rx(m), rr(m), rq(m), rz(m), rp(m);
    if (o.p1_assembled) {
        amg->to_rows(raw(b), raw(rb));
        BP_CK(cudaStreamSynchronize(stream));
    }
    auto rows_apply = [&](const double* in, double* out, cudaStream_t) { amg->apply_rows(in, out); };
    auto rows_cycle = [&](const double* in, double* out, cudaStream_t) {
        BP_CK(cudaStreamSynchronize(stream));
        const auto c0 = std::chrono::steady_clock::now();
        amg->solve_rows(in, out);
        coarse_s += std::chrono::duration<double>(std::chrono::steady_clock::now() - c0).count();
    };
#endif
    for (int k = 0; k < o.solves; ++k) {
        const bool last = k + 1 == o.solves;
        coarse_s = 0.0;   // of the last solve
        if (last && o.profile) {
            BP_CK(cudaDeviceSynchronize());
            BP_CK(cudaProfilerStart());
        }
        BP_CK(cudaEventRecord(t0, stream));
#ifdef MARS_ENABLE_HYPRE
        if (o.p1_assembled)
            res = cellwise::fcg(rows_apply, cellwise::CyclePrecond<decltype(rows_cycle)>{rows_cycle, m}, raw(rb),
                                raw(rx), m, raw(rr), raw(rq), raw(rz), raw(rp), red, o.tol, o.maxit, stream);
        else
#endif
            res = o.mg ? solve(cellwise::CyclePrecond<decltype(cycle)>{cycle, N}) : solve(precond);
        BP_CK(cudaEventRecord(t1, stream));
        BP_CK(cudaEventSynchronize(t1));
        if (last && o.profile) BP_CK(cudaProfilerStop());
        BP_CK(cudaEventElapsedTime(&solve_ms, t0, t1));
        solve_times.push_back((float)all_max(solve_ms));
    }
#ifdef MARS_ENABLE_HYPRE
    if (o.p1_assembled) amg->from_rows(raw(rx), raw(x));
#endif
    // The true assembled residual over the free nodes, relative to that of b.
    apply(raw(x), raw(y), stream);
    residual_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(s), raw(b), raw(y), N);
    cellwise::dss<P>(raw(s), raw(r), topo, h, stream);
    cellwise::dss<P>(raw(b), raw(q), topo, h, stream);
    if (bp3) {
        cellwise::zero_dirichlet<P>(raw(r), topo, stream);
        cellwise::zero_dirichlet<P>(raw(q), topo, stream);
    }
    const double true_rel = counted_norm<P>(raw(r), topo, stream) / counted_norm<P>(raw(q), topo, stream);
    difference_kernel<<<blocks_for(N), cellwise::kThreads, 0, stream>>>(raw(s), raw(x), raw(u), N);
    BP_CK(cudaStreamSynchronize(stream));
    const double err = all_max(thrust::reduce(s.begin(), s.end(), 0.0, thrust::maximum<double>()));
    double umax = 0.0;
    {
        std::vector<double> hu(N);
        thrust::copy(u.begin(), u.end(), hu.begin());
        for (double v : hu) umax = std::fmax(umax, std::fabs(v));
        umax = all_max(umax);
    }
    // --rhs pde: ||x_h - u||_L2 / ||u||_L2 with the q = p + 2 rule.
    double l2_err = 0.0;
    if (pde) {
        thrust::device_vector<double> e2(E * q3), u2(E * q3);
        l2_kernel<P><<<blocks_for(E * q3), cellwise::kThreads, 0, stream>>>(raw(x), E, o.ne, o.deform,
                                                                           rule_of(fine), raw(e2), raw(u2));
        BP_CK(cudaGetLastError());
        BP_CK(cudaStreamSynchronize(stream));
        l2_err = std::sqrt(all_sum(thrust::reduce(e2.begin(), e2.end(), 0.0)) /
                           all_sum(thrust::reduce(u2.begin(), u2.end(), 0.0)));
    }

    auto time_ms = [&](auto&& f) {
        f();
        BP_CK(cudaEventRecord(t0, stream));
        for (int i = 0; i < o.reps; ++i) f();
        BP_CK(cudaEventRecord(t1, stream));
        BP_CK(cudaEventSynchronize(t1));
        float ms = 0.0f;
        BP_CK(cudaEventElapsedTime(&ms, t0, t1));
        return (float)all_max(ms / o.reps);   // the slowest rank
    };
    const float op_ms = time_ms([&] { apply(raw(u), raw(y), stream); });
    const float dss_ms = time_ms([&] { dss(raw(y), raw(s), stream); });
    const float both_ms = time_ms([&] {
        apply(raw(u), raw(y), stream);
        dss(raw(y), raw(s), stream);
    });
    // The p = 1 DSS on its own: a coarse solve makes two, the rest is BoomerAMG.
    float dss1_ms = 0.0f;
    if (o.amg) {
        thrust::device_vector<double> a1(E * 8, 1.0), b1(E * 8);
        BP_CK(cudaDeviceSynchronize());   // filled on the default stream
        dss1_ms = time_ms([&] { cellwise::dss<1>(raw(a1), raw(b1), topo, h1, stream); });
    }
    float rows_ms = 0.0f;   // p1_assembled: the SpMV on the rows
#ifdef MARS_ENABLE_HYPRE
    if (o.p1_assembled) rows_ms = time_ms([&] { amg->apply_rows(raw(rx), raw(rq)); });
#endif
    // Bytes per GPU (this rank's), rates over all ranks.
    const double op_bytes = (2.0 * N + (double)E * (tri ? 24 : K * q3)) * 8.0, dss_bytes = 2.0 * N * 8.0;
    solve_ms = solve_times.back();
    setup_ms = (float)all_max(setup_ms);
    coarse_s = all_max(coarse_s);
    amg_setup_ms = all_max(amg_setup_ms);
    const bool pass = std::fabs(oracle_err) <= 1e-12 * oracle_scale &&
                      (bp3 ? max1 <= 1e-12 * maxv : std::fabs(sum1 - 1.0) <= 1e-12) && (pde || err <= 1e-8 * umax) &&
                      block_err <= 1e-13 * block_scale && block_bits == 0;

    if (root) {
        if (meshed) {
            printf("%s, p=%d, q=%d, mesh %s: %lld elements, %lld unique DoFs, %lld cell-wise, %s geometry\n",
                   o.spec.c_str(), P, Q, o.mesh.c_str(), mt.global, unique, N_all,
                   tri ? "trilinear (corners)" : "stored");
            printf("  read and partitioned in %.1f s; %lld elements mirrored to a right-handed corner order\n",
                   read_s, mt.mirrored);
            if (dec.size > 1)
                printf("  %d ranks (Morton chunks); rank 0: %lld elements, %lld ghosts, %d peers\n", dec.size, E,
                       topo.elements - topo.local, h->peers());
        } else {
            printf("%s, p=%d, q=%d, %d^3 elements (%lld), %lld unique DoFs, %lld cell-wise, deform %.3f, %s geometry\n",
                   o.spec.c_str(), P, Q, o.ne, (long long)o.ne * o.ne * o.ne, unique, N_all, o.deform,
                   tri ? "trilinear (corners)" : "stored");
            if (dec.size > 1)
                printf("  %d ranks (%d x %d x %d); rank 0: %d x %d x %d elements, %lld ghosts, %d peers\n", dec.size,
                       dec.P[0], dec.P[1], dec.P[2], box.nx, box.ny, box.nz, topo.elements - topo.local, h->peers());
        }
        if (Bk != o.ne || o.rotate)
            printf("  blocks of %d^3 elements (%lld)%s\n", Bk, nblocks, o.rotate ? ", rotated" : "");
        if (!o.block_dss.empty())
            printf("  block DSS (%s) vs hand gather, random vector: max diff %.1e of max %.1e\n", o.block_dss.c_str(),
                   block_err, block_scale);
        if (block_gen) printf("  generated vs hand block nodes: %lld copies differ in their bits\n", block_bits);
        if (bp3)
            printf("  BP3 applied to 1: max %.1e (of max %.1e for a random v)\n", max1, maxv);
        else
            printf("  BP1 applied to 1, summed: %.15f (the volume: 1)\n", sum1);
        printf("  first %lld elements vs direct quadrature sums, random v: %.1e of max %.1e\n", Ec, oracle_err,
               oracle_scale);
        if (o.mg)
            printf("  multigrid p=%d%s%s, Chebyshev (%d,%d), coarse %s x%d; lmax %.4f %.4f %.4f; setup %.1f ms\n", P,
                   P == 7 ? " -> 3" : "", P > 1 ? " -> 1" : "", o.pre, o.post, o.amg ? "BoomerAMG" : "Chebyshev",
                   o.amg ? o.amg_cycles : o.coarse, lmax[0], lmax[1], lmax[2], setup_ms);
        if (o.mg && o.cheb_interval == "mfem" && P > 1)
            printf("  Chebyshev interval MFEM's: [0.3, 1.2] lmax, 10 power steps\n");
        if (o.amg)
            printf("  BoomerAMG: strong threshold %.2f, %d aggressive levels, coarsest at most %d rows\n", o.amg_theta,
                   o.amg_agg, o.amg_coarse_size);
        if (o.p1_assembled)
            printf("  FCG on the %lld rows of the assembled p = 1 matrix; SpMV %.3f ms, %.2f GDoF/s\n",
                   (long long)all_sum((double)m), rows_ms, all_sum((double)m) / (rows_ms * 1e6));
        printf("  FCG + %s: %d iterations, sqrt(<r,z>/<r0,z0>) = %.3e, true assembled residual %.3e\n",
               o.mg ? "V-cycle" : "DSS-Jacobi", res.iterations, res.relative, true_rel);
        for (int k : {1, 5, 10, 20, 50, 100})
            if (k <= (int)res.history.size()) printf("  it %3d  %.6e\n", k, res.history[k - 1]);
        if (pde)
            printf("  right-hand side M f_h, f = 3 pi^2 u: L2 error %.3e (relative), at the nodes max |x - u| / "
                   "max |u| = %.3e  %s\n",
                   l2_err, err / umax, pass ? "PASS" : "FAIL");
        else
            printf("  max |x - u| / max |u| = %.3e  %s\n", err / umax, pass ? "PASS" : "FAIL");
        printf("  operator     %8.3f ms  %6.2f GDoF/s unique  %6.2f cell-wise  %6.0f GB/s per GPU (u, y, geometry)\n",
               op_ms, unique / (op_ms * 1e6), N_all / (op_ms * 1e6), op_bytes / (op_ms * 1e6));
        printf("  DSS          %8.3f ms  %6.2f GDoF/s unique  %6.0f GB/s per GPU  (%s)\n", dss_ms,
               unique / (dss_ms * 1e6), dss_bytes / (dss_ms * 1e6),
               block_gen ? "block, MARSIR-generated" : !o.block_dss.empty() ? "block" : dss_gen ? "MARSIR-generated" : "hand gather");
        printf("  operator+DSS %8.3f ms  %6.2f GDoF/s unique  (the assembled operator)\n", both_ms,
               unique / (both_ms * 1e6));
        if (o.solves > 1) {
            printf("  solves");
            for (float t : solve_times) printf(" %.1f", t);
            printf(" ms (the last is reported)\n");
        }
        printf("  FCG iteration %7.3f ms  (solve %.1f ms%s)\n", res.iterations ? solve_ms / res.iterations : 0.0f,
               solve_ms, o.mg ? (", + setup " + std::to_string((int)setup_ms) + " ms").c_str() : "");
        if (o.amg)   // one coarse solve per V-cycle: FCG's iterations + the first
            printf("  coarse solve  %7.3f ms per V-cycle, %.0f%% of the solve (BoomerAMG x%d and two p = 1 DSS of "
                   "%.3f ms); AMG setup %.0f ms\n",
                   coarse_s * 1e3 / (res.iterations + 1), 100.0 * coarse_s * 1e3 / solve_ms, o.amg_cycles, dss1_ms,
                   amg_setup_ms);
    }
    BP_CK(cudaStreamDestroy(stream));
    return pass ? 0 : 1;
}

}  // namespace

int main(int argc, char** argv)
{
    MPI_Init(&argc, &argv);
    int rank = 0, ranks = 1;
    MPI_Comm_rank(MPI_COMM_WORLD, &rank);
    MPI_Comm_size(MPI_COMM_WORLD, &ranks);
    // One GPU per rank, by the rank's index on its node, before any CUDA object exists
    // (the PTX modules and the reductions bind to the current device).
    {
        MPI_Comm node;
        MARS_CELLWISE_MPI(MPI_Comm_split_type(MPI_COMM_WORLD, MPI_COMM_TYPE_SHARED, rank, MPI_INFO_NULL, &node));
        int local = 0, devices = 0;
        MARS_CELLWISE_MPI(MPI_Comm_rank(node, &local));
        MARS_CELLWISE_MPI(MPI_Comm_free(&node));
        MARS_CELLWISE_CK(cudaGetDeviceCount(&devices));
        MARS_CELLWISE_CK(cudaSetDevice(local % devices));
    }
    Options o;
    const char* error = nullptr;
    for (int i = 1; i < argc && !error; i += 2) {
        if (!strcmp(argv[i], "--amg-print") || !strcmp(argv[i], "--profile") || !strcmp(argv[i], "--p1-matrix-free")) {
            (argv[i][2] == 'a' ? o.amg_print : argv[i][3] == 'r' ? o.profile : o.p1_matrix_free) = true;
            --i;
            continue;
        }
        if (!strcmp(argv[i], "--rotate") || !strcmp(argv[i], "--mg") || !strcmp(argv[i], "--amg")) {
            (argv[i][2] == 'r' ? o.rotate : argv[i][2] == 'm' ? o.mg : o.amg) = true;
            --i;
            continue;
        }
        if (i + 1 >= argc) error = "an option needs a value";
        else if (!strcmp(argv[i], "--ptx-dir")) o.ptx_dir = argv[i + 1];
        else if (!strcmp(argv[i], "--spec")) o.spec = argv[i + 1];
        else if (!strcmp(argv[i], "--p")) o.p = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--ne")) o.ne = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--deform")) o.deform = atof(argv[i + 1]);
        else if (!strcmp(argv[i], "--tol")) o.tol = atof(argv[i + 1]);
        else if (!strcmp(argv[i], "--maxit")) o.maxit = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--reps")) o.reps = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--solves")) o.solves = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--cheb-interval")) o.cheb_interval = argv[i + 1];
        else if (!strcmp(argv[i], "--rhs")) o.rhs = argv[i + 1];
        else if (!strcmp(argv[i], "--mesh")) o.mesh = argv[i + 1];
        else if (!strcmp(argv[i], "--dss-ptx")) o.dss_ptx = argv[i + 1];
        else if (!strcmp(argv[i], "--block")) o.block = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--block-dss")) o.block_dss = argv[i + 1];
        else if (!strcmp(argv[i], "--pre")) o.pre = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--post")) o.post = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--coarse")) o.coarse = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--amg-cycles")) o.amg_cycles = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--amg-theta")) o.amg_theta = atof(argv[i + 1]);
        else if (!strcmp(argv[i], "--amg-agg")) o.amg_agg = atoi(argv[i + 1]);
        else if (!strcmp(argv[i], "--amg-coarse-size")) o.amg_coarse_size = atoi(argv[i + 1]);
        else error = "unknown option";
    }
    if (!error && o.ptx_dir.empty()) error = "--ptx-dir is required";
    if (!error && o.spec != "bp1" && o.spec != "bp3" && o.spec != "bp1_tri" && o.spec != "bp3_tri")
        error = "--spec is bp1, bp3, bp1_tri or bp3_tri";
    if (!error && o.p != 1 && o.p != 3 && o.p != 7) error = "--p is 1, 3 or 7 (the generated degrees)";
    if (!error && ranks > 1 && (o.block || o.rotate || !o.block_dss.empty() || !o.dss_ptx.empty()))
        error = "--block, --rotate, --block-dss and --dss-ptx are for one rank";
    if (!error && (o.block < 0 || (o.block && o.ne % o.block))) error = "--block must divide --ne";
    if (!error && o.mg && o.spec.rfind("bp3", 0) != 0) error = "--mg is for bp3 and bp3_tri";
    if (!error && o.amg && !o.mg) error = "--amg goes with --mg";
    if (!error && o.mg && o.p == 1 && !o.amg) error = "--mg at p = 1 needs --amg (the coarse solve is the whole cycle)";
    if (!error && o.amg_cycles < 1) error = "--amg-cycles must be positive";
    if (!error && o.solves < 1) error = "--solves must be positive";
    if (!error && o.cheb_interval != "mars" && o.cheb_interval != "mfem") error = "--cheb-interval is mars or mfem";
    if (!error && o.rhs != "discrete" && !(o.rhs == "pde" && o.spec.rfind("bp3", 0) == 0))
        error = "--rhs is discrete, or pde for bp3 and bp3_tri";
    if (!error && !o.mesh.empty() &&
        (o.spec.rfind("bp3", 0) != 0 || o.rhs == "pde" || o.block || o.rotate || !o.block_dss.empty()))
        error = "--mesh is for bp3 and bp3_tri, without --rhs pde, --block, --rotate or --block-dss";
    if (!error && o.p1_matrix_free && !(o.p == 1 && o.amg)) error = "--p1-matrix-free goes with --p 1 --mg --amg";
    o.p1_assembled = o.p == 1 && o.amg && !o.p1_matrix_free;
    if (!error && (!(o.amg_theta > 0.0 && o.amg_theta < 1.0) || o.amg_agg < 0 || o.amg_coarse_size < 1))
        error = "--amg-theta is in (0, 1), --amg-agg at least 0, --amg-coarse-size at least 1";
#ifndef MARS_ENABLE_HYPRE
    if (!error && o.amg) error = "--amg needs a Hypre build (MARS_ENABLE_HYPRE)";
#endif
    if (!error && !o.block_dss.empty()) {
        if (o.block_dss != "passes" && o.block_dss != "nodes" && o.block_dss != "generated")
            error = "--block-dss is passes, nodes or generated";
        const int b = o.block ? o.block : o.ne;
        if (b != 2 && b != 4 && b != 8 && b != 16 && b != 32) error = "--block-dss needs --block 2, 4, 8, 16 or 32";
        if (!o.dss_ptx.empty()) error = "--block-dss and --dss-ptx exclude each other";
    }
    // The halos pass device pointers to MPI; Cray MPICH accepts them only with
    // MPICH_GPU_SUPPORT_ENABLED=1, and fails later with an unreadable error otherwise.
    if (!error && ranks > 1) {
        char version[MPI_MAX_LIBRARY_VERSION_STRING];
        int len = 0;
        MPI_Get_library_version(version, &len);
        const char* gpu = getenv("MPICH_GPU_SUPPORT_ENABLED");
        if (strstr(version, "MPICH") && !(gpu && !strcmp(gpu, "1")))
            error = "MPICH_GPU_SUPPORT_ENABLED=1 is required on several ranks (GPU-aware MPI)";
    }
    if (error) {
        if (rank == 0)
            fprintf(stderr, "%s\nusage: %s --ptx-dir <dir> --spec bp1|bp3|bp1_tri|bp3_tri --p 1|3|7 [--ne N] [--deform a] [--tol t] "
                            "[--maxit k] [--reps r] [--solves k] [--profile] [--cheb-interval mars|mfem] [--p1-matrix-free] [--rhs discrete|pde] [--mesh file.e] [--dss-ptx file] [--block B] [--rotate] [--block-dss passes|nodes|generated] [--mg [--pre k] [--post k] [--coarse k] [--amg [--amg-cycles k] [--amg-theta t] [--amg-agg k] [--amg-coarse-size n] [--amg-print]]]\n", error, argv[0]);
        MPI_Finalize();
        return 1;
    }
    const int status = o.p == 1 ? run<1>(o) : o.p == 3 ? run<3>(o) : run<7>(o);
    MPI_Finalize();
    return status;
}
