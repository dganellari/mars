// The CEED benchmark problems BP1 (mass) and BP3 (Laplacian) on element-local
// (cell-wise) vectors, with the operators MARSIR generates from marsir-compiler/specs/
// bp1.op and bp3.op (PTX from marsir-mlir/test/bp_gpu_pipeline.py), the unstructured DSS
// (solvers/mars_cellwise_topology.hpp), and the communication-free flexible CG of
// Wichrowski's "Coalesced Matrix-Free Finite Elements in Cell-Wise Storage"
// (solvers/mars_cellwise_fcg.hpp) with DSS + Jacobi.
//
// Mesh: the unit cube as ne^3 trilinear hexahedra deformed by x += a sin(pi x) sin(pi y)
// sin(pi z) (1,1,1), GLL nodes of degree p, q = p + 2 Gauss points. Geometry per Gauss
// point on the GPU: w det J (BP1), the symmetric w det J J^-1 J^-T (BP3).
//
// --spec bp1_tri | bp3_tri: the same operators from specs with `geometry = trilinear`;
// the kernel reads the element's 8 corners and forms the geometry in registers. The
// stored geometry is still built for the checks and the diagonal, then freed before the
// solve and the timing.
//
// Checks: BP1 applied to 1 sums to the volume (1); BP3 applied to 1 is 0; the operator on
// the first elements equals direct quadrature sums on the host, on a random vector. Solve: b = A u with u =
// sin(pi x) sin(pi y) sin(pi z) at the nodes (zero on the boundary for BP3), so FCG
// must return u; its history must match marsir-mlir/test/cellwise_bp_ref.py
// (GPU-comparable run) for the same --spec, --p, --ne, --deform.
//
// Timing (one GPU): the operator apply, the DSS, apply + DSS (the assembled operator, as
// the paper's Table 7), an FCG iteration. Rates are per unique DoF, (ne p + 1)^3; the
// bandwidth counts what one pass must move at least: u and y, and the geometry (stored
// per Gauss point, or the 24 corner coordinates).
//
// --dss-ptx <dss_p{p}_sm90.ptx>: the DSS MARSIR generates from mir.dss
// (marsir-mlir/test/dss_gpu_pipeline.py p; same bits as the hand gather, so the same
// history) instead of the hand dss<P>.
//
// --block B: the elements are stored in blocks of B^3 (B divides ne), block after block,
// lexicographic inside a block (the default B = ne is the plain lexicographic cube).
// --rotate stores each block in one of the 24 proper rotations of its frame, so element
// frames and block interfaces see every orientation. --block-dss passes|nodes uses the
// block DSS (solvers/mars_cellwise_block_dss.hpp: three passes inside the blocks, or one
// thread per block node, then the block skeleton; B = 2, 4, 8, 16 or 32) and checks it
// against the hand gather on a random vector (the sums run in another order: equal to
// rounding). --block-dss generated: the same block nodes + skeleton generated by MARSIR
// (<ptx-dir>/block_dss_p{p}_b{B}_sm90.ptx), also checked bit for bit against the hand
// block nodes.
//
// --mg (BP3): FCG preconditioned by a p-multigrid V-cycle instead of DSS + Jacobi
// (solvers/mars_cellwise_pmg.hpp): levels p -> 3 -> 1 (7 -> 3 -> 1, or 3 -> 1; p = 1 alone
// takes the coarse solve), the BP3 Galerkin form rediscretized at each degree (the
// MARSIR kernels bp3_p{3,1} in --ptx-dir), --pre / --post Chebyshev-Jacobi steps (2 and 2
// by default: equal for a symmetric cycle), on p = 1 --coarse Chebyshev steps or, with --amg,
// BoomerAMG on the assembled p = 1 matrix (--amg-cycles V-cycles, default 3; a Hypre build).
// --amg-theta, --amg-agg and --amg-coarse-size set its hierarchy (cellwise::AmgSettings),
// --amg-print prints Hypre's setup statistics.
// --cheb-interval mfem smooths on MFEM's interval ([0.3, 1.2] lmax, 10 power steps;
// cellwise::ChebyshevInterval) instead of MARS's ([1.1 / 15, 1.1] lmax, 30 steps), so this
// V-cycle is the one of tests/performance/mfem_bp3.
// p = 1 with --mg --amg: FCG on the rows of the assembled p = 1 matrix that BoomerAMG uses,
// as MFEM does (assembled at p = 1, matrix-free above: 2x faster than the cell-wise operator
// here, docs/design/cellwise_bp_fcg.md); b is assembled onto the rows before the timing and
// x put back on every copy after it, for the same checks. --p1-matrix-free keeps the
// matrix-free cell-wise operator. Without --mg, p = 1 is matrix-free (DSS-Jacobi needs no
// matrix).
// --rhs pde (BP3): b = M f_h instead of A u, f = -lap u = 3 pi^2 u (u vanishes on the cube's
// boundary, which the deformation keeps), M the BP1 mass operator generated for the same
// degree and rule (<ptx-dir>/bp1_p{p}_sm90.ptx). The solve then returns the discrete
// solution, and its L2 error (at the Gauss points) and max error at the nodes measure the
// discretization, for the convergence study; tests/performance/mfem_bp3 --rhs pde builds the
// same b.
// --mesh <file.e> (BP3): an Exodus Hex8 mesh instead of the cube (trilinear elements from
// their 8 corners, homogeneous Dirichlet on the whole boundary). Rank 0 reads it and
// broadcasts it; every rank cuts the same partition (elements in Morton order of their
// centroids, equal chunks) and keeps the elements that share a vertex with its chunk as
// ghosts, the closure the DSS needs. u is the same sin product at the nodes, zero on the
// boundary copies, b = A u.
// --solves k runs the solve k times from x = 0 and prints each time; the results reported are
// those of the last (warm) solve. --profile brackets the last solve with cudaProfilerStart /
// Stop (nsys --capture-range=cudaProfilerApi).
// Reference: marsir-mlir/test/cellwise_bp_mg_ref.py. Every solve also reports the TRUE
// assembled residual ||DSS(b - A x)|| over the free nodes, each once, relative to that
// of b: the FCG history sqrt(<r,z>/<r0,z0>) depends on the preconditioner.
//
// Several MPI ranks (one GPU each, by the rank's index on its node; GPU-aware MPI, on Cray
// MPICH MPICH_GPU_SUPPORT_ENABLED=1): each rank owns a sub-block of the cube
// (cellwise::Decomposition), with the ghost elements around it in its tables, and every
// DSS exchanges the shared copies (cellwise::UnstructuredHalo, one per degree). The DSS
// gives the same bits on any rank count and the global sums differ by rounding, so with
// DSS-Jacobi, or the V-cycle with Chebyshev on p = 1, the history must match one rank to
// rounding. BoomerAMG coarsens each partition differently: its iterations may differ a
// little. --block, --rotate, --block-dss and --dss-ptx are for one rank.
//
// Run: mars_marsir_bp --ptx-dir <marsir-mlir/generated> --spec bp3 --p 3 [--ne 32]
//                     [--deform 0.05] [--tol 1e-10] [--maxit 2000] [--reps 20] [--dss-ptx file]
//                     [--block B] [--rotate] [--block-dss passes|nodes|generated]
//                     [--mg [--pre k] [--post k] [--coarse k] [--amg [--amg-cycles k] [--amg-theta t]
//                     [--amg-agg k] [--amg-coarse-size n] [--amg-print]]]

